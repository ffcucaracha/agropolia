import { expect, test } from '@playwright/test'

function validInn(prefix: string): string {
  const weights = [2, 4, 10, 3, 5, 9, 4, 6, 8]
  const check = prefix.split('').reduce((sum, digit, index) => sum + Number(digit) * weights[index], 0) % 11 % 10
  return prefix + String(check)
}

test('I-1 field, observation and task are persisted in the real backend', async ({ page }, testInfo) => {
  await page.goto('/start')
  await page.getByRole('link', { name: 'Зарегистрироваться' }).click()
  await page.getByLabel('Email').fill(`i1-e2e-${testInfo.retry}@example.test`)
  await page.getByRole('button', { name: 'Получить код' }).click()
  const otp = (await page.locator('.dev-note').innerText()).replace(/[^0-9]/g, '')
  await page.getByLabel('Код из письма').fill(otp)
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await page.getByLabel('Имя').fill('Полевой агроном')
  await page.getByLabel('ИНН').fill(validInn(`37000100${testInfo.retry + 1}`))
  await page.getByLabel('Название хозяйства').fill('Хозяйство E2E I-1')
  await page.getByLabel('Согласен на обработку персональных данных').check()
  await page.getByRole('button', { name: 'Создать хозяйство' }).click()
  await expect(page.getByRole('heading', { name: 'Полевой агроном' })).toBeVisible()
  await page.getByRole('link', { name: 'Мои поля' }).click()
  await page.getByRole('link', { name: 'Добавить поле' }).click()
  await page.getByLabel('Название поля').fill('Поле 1')
  await page.getByLabel('Культура').fill('Пшеница')
  await page.getByLabel('Площадь, га').fill('20')
  await page.getByRole('button', { name: 'Сохранить поле' }).click()
  await expect(page.getByRole('heading', { name: 'Поле 1' })).toBeVisible()
  await page.getByRole('link', { name: 'Наблюдения', exact: true }).click()
  await page.getByRole('link', { name: 'Отметить' }).click()
  await page.getByLabel('Поле').selectOption({ label: 'Поле 1' })
  await page.getByLabel('Описание').fill('Изменение окраски листьев')
  await page.getByRole('button', { name: 'Сохранить наблюдение' }).click()
  await expect(page.getByText('Изменение окраски листьев')).toBeVisible()
  await page.locator('a.record-card').first().click()
  await page.getByRole('link', { name: 'Создать задачу' }).click()
  await page.getByLabel('Задача').fill('Осмотр листьев')
  await page.getByRole('button', { name: 'Создать задачу' }).click()
  await page.locator('a.record-card').first().click()
  await page.getByRole('button', { name: 'Принять' }).click()
  await expect(page.getByText('Принята', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Начать работу' }).click()
  await page.getByRole('button', { name: 'Отметить выполненной' }).click()
  await expect(page.getByText('Выполнена', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Проверить выполнение' }).click()
  await page.getByRole('link', { name: 'Журнал работ' }).click()
  await expect(page.getByText('Осмотр листьев')).toBeVisible()
})

test('I-1 offline observation is stored and synced after reconnect', async ({ page, context }, testInfo) => {
  await page.goto('/start')
  await page.getByRole('link', { name: 'Зарегистрироваться' }).click()
  await page.getByLabel('Email').fill(`i1-offline-e2e-${testInfo.retry}@example.test`)
  await page.getByRole('button', { name: 'Получить код' }).click()
  const otp = (await page.locator('.dev-note').innerText()).replace(/[^0-9]/g, '')
  await page.getByLabel('Код из письма').fill(otp)
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await page.getByLabel('Имя').fill('Офлайн агроном')
  await page.getByLabel('ИНН').fill(validInn(`37000100${testInfo.retry + 3}`))
  await page.getByLabel('Название хозяйства').fill('Офлайн хозяйство')
  await page.getByLabel('Согласен на обработку персональных данных').check()
  await page.getByRole('button', { name: 'Создать хозяйство' }).click()
  await page.getByRole('link', { name: 'Мои поля' }).click()
  await page.getByRole('link', { name: 'Добавить поле' }).click()
  await page.getByLabel('Название поля').fill('Поле офлайн')
  await page.getByLabel('Культура').fill('Овёс')
  await page.getByLabel('Площадь, га').fill('20')
  await page.getByRole('button', { name: 'Сохранить поле' }).click()
  await page.getByRole('link', { name: 'Наблюдения', exact: true }).click()
  await context.setOffline(true)
  await page.getByRole('link', { name: 'Отметить' }).click()
  await page.getByLabel('Поле').selectOption({ label: 'Поле офлайн' })
  await page.getByLabel('Описание').fill('Без сети')
  await page.getByRole('button', { name: 'Сохранить наблюдение' }).click()
  await expect(page.getByText('Без сети')).toBeVisible()
  await context.setOffline(false)
  await page.waitForTimeout(1500)
  await page.reload()
  await page.getByRole('link', { name: 'Наблюдения', exact: true }).click()
  await expect(page.getByText('Без сети')).toBeVisible()
})
